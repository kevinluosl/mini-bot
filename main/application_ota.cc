// OTA 升级与设备激活流程。
//
// 从 application.cc 拆分而来：这些函数都属于"设备上线与固件生命周期"，
// 与聊天状态机、音频通道无关，独立成编译单元后职责更清晰。
// 函数仍为 Application 成员（声明在 application.h），行为与拆分前一致。

